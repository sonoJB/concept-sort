A = {sc: json.load(open(f"{d}/analysis_{sc}.json", encoding="utf-8")) for sc in ["KR", "JP", "ALL"]}


def sol(sc, k):
    return next(s for s in A[sc]["solutions"] if s["k"] == k)


def height(sc, clusters_after):
    m = next(r for r in A[sc]["ward"]["merges"] if r["clustersAfter"] == clusters_after)
    return m["height"]


def nums(sc, k):
    return ",".join(str(i + 1) for i in sol(sc, k)["clusters"][0]["members"])


def cl(cluster, nameKo, nameJa, core, basis, rep):
    return dict(cluster=cluster, nameKo=nameKo, nameJa=nameJa, coreContentKo=core, basisKo=basis, representativeStatements=rep)


